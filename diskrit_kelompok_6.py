"""
Studi Kasus: Sistem Pencarian Rute Terpendek (metode Traveling Salesman Problem)
Skill Lab yang dipakai:
  - Skill Lab 5  : Graf Berbobot       (model jalan antar lokasi)
  - Skill Lab 14 : Lintasan Terpendek  (Dijkstra -> matriks jarak antar lokasi)
  - Skill Lab 13 : Sirkuit Hamilton    (brute force permutasi = TSP)

CATATAN: jarak di bawah adalah CONTOH (km). Ganti dengan jarak sebenarnya.
"""
import itertools
import networkx as nx
import matplotlib.pyplot as plt

# ---------------------------------------------------------------
# 1. Graf berbobot jalan raya (Skill Lab 5)
# ---------------------------------------------------------------
G = nx.Graph()
G.add_weighted_edges_from([
    ("Kost",      "Pertamina", 1.1),
    ("Kost",      "Fotokopi",  1.2),
    ("Kost",      "Makan",     1.1),
    ("Pertamina", "Fotokopi",  0.8),
    ("Pertamina", "Kampus",    0.95),
    ("Fotokopi",  "Makan",     0.09),
    ("Makan",     "Kampus",    0.7),
])

print("=== GRAF JALAN ===")
for u, v, w in G.edges(data="weight"):
    print(f"{u} - {v}: {w} km")

# ---------------------------------------------------------------
# 2. Jarak terpendek tiap pasangan lokasi (Skill Lab 14 - Dijkstra)
#    Dipakai karena tidak semua lokasi punya jalan langsung,
#    contoh: Kost - Kampus.
# ---------------------------------------------------------------
lokasi = list(G.nodes())
jarak = {}
for a in lokasi:
    for b in lokasi:
        if a != b:
            jarak[(a, b)] = nx.shortest_path_length(G, a, b, weight="weight")

print("\n=== JARAK TERPENDEK ANTAR LOKASI (Dijkstra) ===")
for a, b in itertools.combinations(lokasi, 2):
    print(f"{a} - {b}: {jarak[(a, b)]:.1f} km")

# ---------------------------------------------------------------
# 3. TSP brute force (Skill Lab 13): semua sirkuit berawal & berakhir di Kost
# ---------------------------------------------------------------
awal = "Kost"
lainnya = [x for x in lokasi if x != awal]


def total(rute):
    return sum(jarak[(rute[i], rute[i + 1])] for i in range(len(rute) - 1))


semua = []
for perm in itertools.permutations(lainnya):
    rute = [awal] + list(perm) + [awal]
    semua.append((rute, total(rute)))
semua.sort(key=lambda x: x[1])

print(f"\n=== TSP TANPA BATASAN: {len(semua)} kemungkinan rute ===")
for rute, d in semua[:5]:
    print(" -> ".join(rute), f"= {d:.1f} km")
print("Rute terpendek (tanpa batasan):", " -> ".join(semua[0][0]), f"= {semua[0][1]:.1f} km")


# ---------------------------------------------------------------
# 4. TSP dengan batasan urutan sesuai soal:
#    Pertamina & Fotokopi harus SEBELUM Kampus, Makan harus SESUDAH Kampus
# ---------------------------------------------------------------
def valid(rute):
    i = rute.index
    return i("Pertamina") < i("Kampus") and i("Fotokopi") < i("Kampus") and i("Kampus") < i("Makan")


berbatas = [(r, d) for r, d in semua if valid(r)]
print(f"\n=== TSP DENGAN BATASAN URUTAN: {len(berbatas)} rute valid ===")
for rute, d in berbatas:
    print(" -> ".join(rute), f"= {d:.1f} km")

terbaik, d_terbaik = berbatas[0]
print("\nRute terbaik (dengan batasan):", " -> ".join(terbaik))
print(f"Total jarak: {d_terbaik:.1f} km")

# Pembanding: urutan persis seperti teks soal
urutan_soal = ["Kost", "Pertamina", "Fotokopi", "Kampus", "Makan", "Kost"]
d_soal = total(urutan_soal)
print("\nUrutan sesuai soal :", " -> ".join(urutan_soal), f"= {d_soal:.1f} km")
print(f"Selisih dengan rute terbaik: {d_soal - d_terbaik:.1f} km")

# Rincian jalan sebenarnya yang dilalui rute terbaik
print("\nRincian jalan rute terbaik:")
for i in range(len(terbaik) - 1):
    a, b = terbaik[i], terbaik[i + 1]
    jalur = nx.shortest_path(G, a, b, weight="weight")
    print(f"  {a} -> {b}: {' -> '.join(jalur)} ({jarak[(a, b)]:.1f} km)")

# ---------------------------------------------------------------
# 5. Visualisasi (Skill Lab 5): rute terbaik disorot
# ---------------------------------------------------------------
pos = nx.spring_layout(G, seed=7)
plt.figure(figsize=(8, 6))
nx.draw(G, pos, with_labels=True, node_size=2200, node_color="#dbeafe",
        font_size=9, edge_color="#9ca3af")
nx.draw_networkx_edge_labels(G, pos, edge_labels=nx.get_edge_attributes(G, "weight"))

sisi_rute = []
for i in range(len(terbaik) - 1):
    jalur = nx.shortest_path(G, terbaik[i], terbaik[i + 1], weight="weight")
    sisi_rute += list(zip(jalur[:-1], jalur[1:]))
nx.draw_networkx_edges(G, pos, edgelist=sisi_rute, edge_color="red", width=3)

plt.title(f"Rute TSP terbaik: {d_terbaik:.1f} km")
plt.savefig("rute_tsp.png", dpi=150, bbox_inches="tight")
plt.show()